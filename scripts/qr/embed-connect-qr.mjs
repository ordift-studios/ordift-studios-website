// Embeds the approved permanent QR master files (brand/qr/) into the Super Admin QR Code Manager.
//
//   node scripts/qr/embed-connect-qr.mjs
//
// The master files are the single source of truth. This script only copies their bytes into src/lib/qr/connectQrMaster.generated.ts so the files travel with the application build
// (the Super Admin page and its downloads then never depend on the file system at run time). A test pins the embedded bytes to the files in brand/qr/, so the two can never drift apart.
// It generates nothing and changes nothing about the code itself: if the master files are ever replaced, run this again and the test confirms the match.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const dir = join(root, "brand/qr");
const PNG_NAME = "ordift-studios-connect-qr.png";
const SVG_NAME = "ordift-studios-connect-qr.svg";

const png = readFileSync(join(dir, PNG_NAME));
const svg = readFileSync(join(dir, SVG_NAME));
const sha = (b) => createHash("sha256").update(b).digest("hex");

if (png.subarray(0, 8).toString("hex") !== "89504e470d0a1a0a") throw new Error("The PNG master is not a PNG file.");
const width = png.readUInt32BE(16), height = png.readUInt32BE(20), bitDepth = png[24];
if (width !== height) throw new Error("The PNG master must be square.");
if (!svg.toString("utf8").includes("<svg")) throw new Error("The SVG master is not an SVG file.");

const body = `// GENERATED by scripts/qr/embed-connect-qr.mjs from the approved master files in brand/qr/. Do not edit by hand.
// A test checks that these bytes are identical to the files in brand/qr/ (and to the checksums recorded in brand/qr/README.md).
export const CONNECT_QR_MASTER = {
  // The one fixed address the permanent QR code opens. It is a literal, never read from settings, the environment or user input.
  destination: "https://ordiftstudios.com/connect",
  png: {
    filename: ${JSON.stringify(PNG_NAME)},
    sha256: ${JSON.stringify(sha(png))},
    bytes: ${png.length},
    width: ${width},
    height: ${height},
    bitDepth: ${bitDepth},
    base64: ${JSON.stringify(png.toString("base64"))},
  },
  svg: {
    filename: ${JSON.stringify(SVG_NAME)},
    sha256: ${JSON.stringify(sha(svg))},
    bytes: ${svg.length},
    text: ${JSON.stringify(svg.toString("utf8"))},
  },
} as const;
`;
writeFileSync(join(root, "src/lib/qr/connectQrMaster.generated.ts"), body);
console.log(`embedded ${PNG_NAME} (${png.length} bytes, ${width}x${height}, sha256 ${sha(png).slice(0, 12)}...) and ${SVG_NAME} (${svg.length} bytes, sha256 ${sha(svg).slice(0, 12)}...)`);
